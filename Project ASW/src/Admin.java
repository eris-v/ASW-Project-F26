import java.time.LocalDate;

public class Admin extends User {
    private AdminRole role;
    private String[] permissions;
    private String department;

    public Admin(Integer userID, String name, String email, String password, String username, LocalDate birthDate, boolean isActive, AdminRole role, String[] permissions, String department) {
        super(userID, name, email, password, username, birthDate, isActive);
        this.role = role;
        this.permissions = permissions;
        this.department = department;
    }

    public void suspendUser(User user) {
        suspendUser(user, Database.getInstance());
    }

    public void suspendUser(User user, Database db) {
        if (user != null) {
            user.deactivateAccount();
            if (db != null) {
                db.updateUser(user);
            }
        }
    }

    public boolean suspendUserById(Integer userID, Database db) {
        if (userID == null || db == null) {
            return false;
        }
        User user = db.findUserById(userID);
        if (user != null) {
            suspendUser(user, db);
            return true;
        }
        return false;
    }

    public boolean approvePublisher(Publisher publisher) {
        return approvePublisher(publisher, Database.getInstance());
    }

    public boolean approvePublisher(Publisher publisher, Database db) {
        if (publisher != null && publisher.getLicense() != null && !publisher.getLicense().isBlank()) {
            publisher.activateAccount();
            if (db != null) {
                if (db.findUserById(publisher.getUserID()) == null) {
                    db.addUser(publisher);
                } else {
                    db.updateUser(publisher);
                }
            }
            return true;
        }
        return false;
    }

    public boolean removeCatalogItem(Integer itemID) {
        return removeCatalogItem(itemID, Database.getInstance());
    }

    public boolean removeCatalogItem(Integer itemID, Database db) {
        if (itemID == null || db == null) {
            return false;
        }
        Item item = db.findItemById(itemID);
        if (item != null && item.getPublisher() != null) {
            item.getPublisher().getPublishedItems().remove(item);
        }
        boolean removed = db.removeItem(itemID);
        if (removed) {
            System.out.println("Admin " + getUsername() + " removed catalog item ID: " + itemID);
        }
        return removed;
    }

    public void managePermissions(User user, String[] perms) {
        managePermissions(user, perms, Database.getInstance());
    }

    public void managePermissions(User user, String[] perms, Database db) {
        if (user instanceof Admin targetAdmin && perms != null) {
            targetAdmin.setPermissions(perms);
            if (db != null) {
                db.updateUser(targetAdmin);
            }
        }
    }

    public String generateSystemReport() {
        return generateSystemReport(Database.getInstance());
    }

    public String generateSystemReport(Database db) {
        Database targetDb = (db != null) ? db : Database.getInstance();
        return String.format(
                "System Report generated by %s (%s - %s) on %s | Users: %d (Members: %d, Publishers: %d, Admins: %d) | Items: %d (%d available) | Checkouts: %d | Active Loans: %d | Overdue Loans: %d",
                getName(), role, department, LocalDate.now(),
                targetDb.getUsers().size(),
                targetDb.getAllMembers().size(),
                targetDb.getAllPublishers().size(),
                targetDb.getAllAdmins().size(),
                targetDb.getItems().size(),
                targetDb.getAvailableItems().size(),
                targetDb.getCheckouts().size(),
                targetDb.getActiveLoans().size(),
                targetDb.getOverdueLoans().size()
        );
    }

    public AdminRole getRole() {
        return role;
    }

    public void setRole(AdminRole role) {
        this.role = role;
    }

    public String[] getPermissions() {
        return permissions;
    }

    public void setPermissions(String[] permissions) {
        this.permissions = permissions;
    }

    public String getDepartment() {
        return department;
    }

    public void setDepartment(String department) {
        this.department = department;
    }
}
